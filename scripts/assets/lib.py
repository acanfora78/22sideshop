"""Shared helpers for the 22SIDE procedural art-direction pipeline.

Every image in /public/media is generated by these scripts so that the demo
ships with zero third-party / unlicensed photography. Replace the files in
/public/media with real campaign photography when the brand provides it —
file names are referenced from src/content/media.ts.
"""
from __future__ import annotations

import math
import os
import random

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, "fonts")
OUT = os.path.abspath(os.path.join(HERE, "..", "..", "public", "media"))

SHADOW = np.array([8, 8, 8], dtype=np.float32)
HIGHLIGHT = np.array([232, 229, 223], dtype=np.float32)
RED = np.array([139, 23, 23], dtype=np.float32)
RED_LIGHT = np.array([214, 46, 38], dtype=np.float32)


def font(name: str, size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(os.path.join(FONTS, name), size)


def rng(seed: int) -> np.random.Generator:
    random.seed(seed)
    return np.random.default_rng(seed)


def value_noise(w: int, h: int, scale: float, g: np.random.Generator) -> np.ndarray:
    """Smooth noise in [0,1] sampled at roughly `scale` pixels per cell."""
    sw, sh = max(2, int(w / scale) + 2), max(2, int(h / scale) + 2)
    small = (g.random((sh, sw)) * 255).astype(np.uint8)
    img = Image.fromarray(small, "L").resize((w, h), Image.BICUBIC)
    return np.asarray(img, dtype=np.float32) / 255.0


def fbm(w: int, h: int, g: np.random.Generator, base: float = 400, octaves: int = 5) -> np.ndarray:
    acc = np.zeros((h, w), np.float32)
    amp, tot, sc = 1.0, 0.0, base
    for _ in range(octaves):
        acc += value_noise(w, h, sc, g) * amp
        tot += amp
        amp *= 0.5
        sc /= 2.0
    return acc / tot


def to_arr(img: Image.Image) -> np.ndarray:
    return np.asarray(img, dtype=np.float32) / 255.0


def to_img(arr: np.ndarray) -> Image.Image:
    return Image.fromarray((np.clip(arr, 0, 1) * 255).astype(np.uint8), "L")


def blur(arr: np.ndarray, r: float) -> np.ndarray:
    return to_arr(to_img(arr).filter(ImageFilter.GaussianBlur(r)))


def hblur(arr: np.ndarray, r: int) -> np.ndarray:
    """Horizontal motion blur via box filter on a 1-row-high resample."""
    img = to_img(arr)
    w, h = img.size
    small = img.resize((max(1, w // r), h), Image.BOX)
    return to_arr(small.resize((w, h), Image.BILINEAR))


def vblur(arr: np.ndarray, r: int) -> np.ndarray:
    img = to_img(arr)
    w, h = img.size
    small = img.resize((w, max(1, h // r)), Image.BOX)
    return to_arr(small.resize((w, h), Image.BILINEAR))


def glow(arr: np.ndarray, threshold: float = 0.6, radius: float = 18, strength: float = 0.8) -> np.ndarray:
    bright = np.clip((arr - threshold) / (1 - threshold), 0, 1)
    return arr + blur(bright, radius) * strength + blur(bright, radius * 4) * strength * 0.6


def vignette(w: int, h: int, power: float = 0.55) -> np.ndarray:
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    nx, ny = (x / w - 0.5) * 2, (y / h - 0.5) * 2
    d = np.sqrt(nx ** 2 * 0.8 + ny ** 2)
    return np.clip(1 - (d ** 2.2) * power, 0, 1)


def tone(arr: np.ndarray, contrast: float = 1.25, gamma: float = 1.0, lift: float = 0.0) -> np.ndarray:
    a = np.clip(arr, 0, 1) ** gamma
    a = (a - 0.5) * contrast + 0.5
    return np.clip(a + lift, 0, 1)


def grain(arr: np.ndarray, g: np.random.Generator, amount: float = 0.07) -> np.ndarray:
    h, w = arr.shape
    n = g.normal(0, 1, (h, w)).astype(np.float32)
    # Film grain is stronger in mid-tones.
    mid = 1 - np.abs(arr - 0.5) * 1.4
    return arr + n * amount * np.clip(mid, 0.25, 1)


def finish(
    arr: np.ndarray,
    g: np.random.Generator,
    *,
    contrast: float = 1.2,
    gamma: float = 1.0,
    vig: float = 0.55,
    grain_amt: float = 0.06,
    accent: np.ndarray | None = None,
) -> Image.Image:
    h, w = arr.shape
    a = tone(arr, contrast, gamma)
    a = a * vignette(w, h, vig)
    a = grain(a, g, grain_amt)
    a = np.clip(a, 0, 1)
    rgb = SHADOW + (HIGHLIGHT - SHADOW) * a[..., None]
    if accent is not None:
        acc = np.clip(accent, 0, 1)[..., None]
        rgb = rgb * (1 - acc * 0.6) + RED_LIGHT * acc
    return Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8), "RGB")


def save(img: Image.Image, name: str, quality: int = 82) -> None:
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    if name.endswith(".webp"):
        img.save(path, "WEBP", quality=quality, method=6)
    else:
        img.save(path, "JPEG", quality=quality, optimize=True, progressive=True)
    print("wrote", path, img.size)


class Canvas:
    """Supersampled grayscale drawing surface (values 0-255)."""

    def __init__(self, w: int, h: int, ss: int = 2, fill: int = 0):
        self.w, self.h, self.ss = w, h, ss
        self.img = Image.new("L", (w * ss, h * ss), fill)
        self.d = ImageDraw.Draw(self.img)

    def S(self, pts):
        s = self.ss
        return [(x * s, y * s) for x, y in pts]

    def poly(self, pts, fill):
        self.d.polygon(self.S(pts), fill=int(fill))

    def rect(self, x0, y0, x1, y1, fill):
        s = self.ss
        self.d.rectangle([x0 * s, y0 * s, x1 * s, y1 * s], fill=int(fill))

    def line(self, pts, fill, width):
        self.d.line(self.S(pts), fill=int(fill), width=max(1, int(width * self.ss)), joint="curve")

    def ellipse(self, x0, y0, x1, y1, fill):
        s = self.ss
        self.d.ellipse([x0 * s, y0 * s, x1 * s, y1 * s], fill=int(fill))

    def arr(self) -> np.ndarray:
        return to_arr(self.img.resize((self.w, self.h), Image.LANCZOS))


def catmull(points, samples: int = 10, closed: bool = True):
    pts = list(points)
    n = len(pts)
    out = []
    rng_ = range(n) if closed else range(n - 1)
    for i in rng_:
        p0 = pts[(i - 1) % n] if closed or i > 0 else pts[0]
        p1 = pts[i]
        p2 = pts[(i + 1) % n]
        p3 = pts[(i + 2) % n] if closed or i + 2 < n else pts[-1]
        for t in np.linspace(0, 1, samples, endpoint=False):
            t2, t3 = t * t, t * t * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            out.append((x, y))
    if not closed:
        out.append(pts[-1])
    return out


def lerp(a, b, t):
    return a + (b - a) * t


def radial(w: int, h: int, cx: float, cy: float, r: float) -> np.ndarray:
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2) / r
    return np.clip(1 - d, 0, 1) ** 2


def hooded_figure(c: Canvas, cx: float, base_y: float, height: float, fill: int, rim: int | None = None):
    """Original silhouette: oversized hoodie, hands in pocket, baggy pants."""
    s = height
    pts = [
        (0.0, 0.0),  # hood top
        (0.07, 0.012), (0.105, 0.05), (0.11, 0.1), (0.1, 0.135),  # hood right
        (0.17, 0.165), (0.215, 0.2), (0.235, 0.27),  # shoulder drop
        (0.245, 0.37), (0.255, 0.46), (0.25, 0.53),  # sleeve outer
        (0.215, 0.56),  # cuff / hem
        (0.19, 0.575), (0.175, 0.62),  # hem → pants
        (0.165, 0.75), (0.16, 0.88), (0.165, 0.975), (0.185, 1.0),  # right leg outer + shoe
        (0.06, 1.0), (0.045, 0.975), (0.04, 0.85), (0.02, 0.7), (0.0, 0.64),  # right leg inner
        (-0.02, 0.7), (-0.04, 0.85), (-0.045, 0.975), (-0.06, 1.0),  # left inner
        (-0.19, 1.0), (-0.168, 0.975), (-0.162, 0.88), (-0.168, 0.75), (-0.178, 0.62),
        (-0.195, 0.575), (-0.22, 0.56),
        (-0.252, 0.53), (-0.258, 0.46), (-0.248, 0.37), (-0.237, 0.27), (-0.215, 0.2),
        (-0.17, 0.165), (-0.1, 0.135), (-0.11, 0.1), (-0.105, 0.05), (-0.07, 0.012),
    ]
    sm = catmull(pts, 8)
    path = [(cx + x * s, base_y - s + y * s) for x, y in sm]
    if rim is not None:
        # rim light: slightly larger lighter outline behind
        c.poly([(cx + (x) * s * 1.012, base_y - s + y * s - 1) for x, y in sm], rim)
    c.poly(path, fill)
