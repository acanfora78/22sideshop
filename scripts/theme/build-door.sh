#!/usr/bin/env bash
# Regenerate shopify-theme/snippets/door-scene.liquid from the React intro scene.
set -euo pipefail
cd "$(dirname "$0")/../.."
ESBUILD=${ESBUILD:-npx --yes esbuild@0.25.0}
$ESBUILD scripts/theme/render-door.tsx --bundle --platform=node --format=cjs --jsx=automatic --outfile=/tmp/render-door.cjs --alias:@=./src --log-level=error
{ echo "{%- comment -%} Generated by scripts/theme/build-door.sh from src/components/home/DoorScene.tsx — do not edit by hand. {%- endcomment -%}"; NODE_PATH=./node_modules node /tmp/render-door.cjs; echo; } > shopify-theme/snippets/door-scene.liquid
echo "door-scene.liquid updated"
